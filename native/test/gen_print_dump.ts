/*
 * Generates test/b1_print_dump.h: the B1 connect handshake from niimbluelib's
 * test dumps plus fake printer responses for a full print job, so the C test
 * can print against the virtual client.
 *
 * Run: npm run gen-test-dump
 */
import { writeFileSync } from "node:fs";
import { NiimbotPacket, PacketGenerator, ResponseCommandId, Utils, LabelType, PageColorType } from "../../src";
import { B1_V5_22 } from "../../src/test/dumps";

const hex = (p: NiimbotPacket) => Utils.bufToHex(p.toBytes(), " ");
const prefix = (p: NiimbotPacket) => Utils.bufToHex(p.toBytes().slice(0, 3), " ") + " *";

const ok = (req: NiimbotPacket) => {
  const id = req.validResponseIds[0];
  if (id === undefined) throw new Error(`no response id for ${req.command}`);
  return new NiimbotPacket(id, [1]);
};

const lines: string[] = [];
const add = (req: NiimbotPacket, resp: NiimbotPacket | undefined, comment: string) => {
  lines.push(`>> ${prefix(req)} (${comment})`);
  lines.push(`<< ${resp ? hex(resp) : "NA"}`);
};

add(PacketGenerator.setDensity(3), ok(PacketGenerator.setDensity(3)), "SetDensity");
add(PacketGenerator.setLabelType(LabelType.WithGaps), ok(PacketGenerator.setLabelType(1)), "SetLabelType");
const ps = PacketGenerator.printStart7b(1, PageColorType.SingleColor);
add(ps, ok(ps), "PrintStart");
add(PacketGenerator.pageStart(), ok(PacketGenerator.pageStart()), "PageStart");
const sz = PacketGenerator.setPageSize6b(1, 8, 1);
add(sz, ok(sz), "SetPageSize");
// image rows are one-way packets: no response
for (const cmd of ["85", "83", "84", "8a", "8d"]) {
  lines.push(`>> 55 55 ${cmd} * (image row)`);
  lines.push("<< NA");
}
add(PacketGenerator.pageEnd(), ok(PacketGenerator.pageEnd()), "PageEnd");
// page 1 printed, 100% print + feed
add(PacketGenerator.printStatus(), new NiimbotPacket(ResponseCommandId.In_PrintStatus, [0, 1, 100, 100]), "PrintStatus");
add(PacketGenerator.printEnd(), ok(PacketGenerator.printEnd()), "PrintEnd");

const dump = B1_V5_22.trim() + "\n" + lines.join("\n") + "\n";
const c = `/* AUTO-GENERATED by test/gen_print_dump.ts - B1 connect + print job */
static const char *B1_PRINT_DUMP =
${dump
  .split("\n")
  .filter((l) => l.length)
  .map((l) => `  "${l}\\n"`)
  .join("\n")};
`;
writeFileSync(new URL("./b1_print_dump.h", import.meta.url), c);
writeFileSync(new URL("../go/testdata/b1_print_dump.txt", import.meta.url), dump);
console.log(dump);
