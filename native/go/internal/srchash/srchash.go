// Package srchash describes the cgo wrapper files and hashes their sources.
package srchash

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"os"
	"path/filepath"
	"sort"
)

// Wrapper is one go/zz_*.c file.
type Wrapper struct {
	Name    string   // file name in go/
	Include string   // path relative to go/
	Deps    []string // globs relative to the project root that affect it
}

var core = []string{"src/*", "include/*", "generated/niim_bundle.c"}
var qjs = []string{"third_party/quickjs/*"}

// Wrappers lists every generated wrapper.
var Wrappers = []Wrapper{
	{"zz_niim_core.c", "../src/niimblue.c", core},
	{"zz_niim_serial.c", "../src/serial.c", core},
	{"zz_niim_bundle.c", "../generated/niim_bundle.c", core},
	{"zz_qjs_quickjs.c", "../third_party/quickjs/quickjs.c", qjs},
	{"zz_qjs_libregexp.c", "../third_party/quickjs/libregexp.c", qjs},
	{"zz_qjs_libunicode.c", "../third_party/quickjs/libunicode.c", qjs},
	{"zz_qjs_dtoa.c", "../third_party/quickjs/dtoa.c", qjs},
}

// Hash returns the SHA-256 over all files matching globs (sorted, name + content).
func Hash(root string, globs []string) (string, error) {
	var files []string
	for _, g := range globs {
		m, err := filepath.Glob(filepath.Join(root, g))
		if err != nil {
			return "", err
		}
		files = append(files, m...)
	}
	sort.Strings(files)
	h := sha256.New()
	for _, f := range files {
		st, err := os.Stat(f)
		if err != nil || st.IsDir() {
			continue
		}
		b, err := os.ReadFile(f)
		if err != nil {
			return "", err
		}
		rel, _ := filepath.Rel(root, f)
		fmt.Fprintf(h, "%s\x00%d\x00", filepath.ToSlash(rel), len(b))
		h.Write(b)
	}
	return hex.EncodeToString(h.Sum(nil)), nil
}

// Render produces the wrapper file content.
func Render(w Wrapper, hash string) string {
	return fmt.Sprintf(`/* Code generated by go/internal/gensrc; DO NOT EDIT.
 * Compiles %s into the Go package (cgo).
 * sources-sha256: %s
 */
#include "%s"
`, w.Include[3:], hash, w.Include)
}
