// Bundles js/bridge.ts + niimbluelib (from source) into one script and emits
// generated/niim_bundle.c, a C array that is compiled into libniimblue.
//
// Usage: node js/build.mjs [--niimbluelib ..] [--no-minify]
//
// The generated C file is committed, so building the native library only
// needs a C compiler. Re-run this script after updating niimbluelib.

import * as esbuild from "esbuild";
import { mkdirSync, writeFileSync, readFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const argValue = (name, def) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : def;
};

const libDir = resolve(root, argValue("--niimbluelib", process.env.NIIMBLUELIB_DIR ?? ".."));
const minify = !args.includes("--no-minify");
const outDir = join(root, "generated");

if (!existsSync(join(libDir, "src", "index.ts"))) {
  console.error(`niimbluelib sources not found in ${libDir} (use --niimbluelib <dir>)`);
  process.exit(1);
}
if (!existsSync(join(libDir, "node_modules"))) {
  console.error(`${libDir}/node_modules missing, run 'npm ci' in niimbluelib first`);
  process.exit(1);
}

const stub = join(root, "js", "stubs", "capacitor.ts");

// bridge.ts imports "../../src" (the parent niimbluelib checkout); redirect that to the chosen dir.
const redirectLib = {
  name: "niimbluelib-dir",
  setup(build) {
    build.onResolve({ filter: /^\.\.\/\.\.\/src$/ }, () => ({ path: join(libDir, "src", "index.ts") }));
  },
};

const result = await esbuild.build({
  entryPoints: [join(root, "js", "bridge.ts")],
  bundle: true,
  write: false,
  format: "iife",
  platform: "neutral",
  mainFields: ["module", "main"],
  target: ["es2020"],
  minify,
  legalComments: "none",
  // Default template fonts (third_party/fonts) are embedded as base64 strings
  loader: { ".ttf": "base64" },
  alias: {
    "@capacitor/core": stub,
    "@capacitor-community/bluetooth-le": stub,
    fs: join(root, "js", "stubs", "empty.ts"),
  },
  nodePaths: [join(libDir, "node_modules")],
  plugins: [redirectLib],
  logLevel: "warning",
});

const js = result.outputFiles[0].contents;
const pkg = JSON.parse(readFileSync(join(libDir, "package.json"), "utf8"));

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "bundle.js"), js);

// Emit as a byte array (string literals hit MSVC's 64 KiB limit).
const lines = [];
for (let i = 0; i < js.length; i += 20) {
  lines.push("  " + Array.from(js.subarray(i, i + 20), (b) => `${b}`).join(",") + ",");
}

const c = `/* AUTO-GENERATED by js/build.mjs - DO NOT EDIT */
/* niimbluelib ${pkg.version} + bridge, ${js.length} bytes${minify ? ", minified" : ""} */
#include <stddef.h>

const char niim_bundle_version[] = "${pkg.version}";
const size_t niim_bundle_size = ${js.length};
const unsigned char niim_bundle[] = {
${lines.join("\n")}
  0
};
`;

writeFileSync(join(outDir, "niim_bundle.c"), c);
console.log(`bundle: ${js.length} bytes (niimbluelib ${pkg.version}) -> generated/niim_bundle.c`);
